-- Initial schema for the book recommendation Telegram bot.
-- Safe to re-run: tables and indexes are created only when absent.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT NOT NULL UNIQUE,
    username VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS moods (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS books (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    author VARCHAR(255),
    description TEXT,
    publication_year INTEGER,
    cover_url TEXT
);

CREATE TABLE IF NOT EXISTS genres (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS mood_searches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    mood_text TEXT NOT NULL,
    matched_mood_id INTEGER REFERENCES moods(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS book_moods (
    book_id INTEGER NOT NULL REFERENCES books(id),
    mood_id INTEGER NOT NULL REFERENCES moods(id),
    PRIMARY KEY (book_id, mood_id)
);

CREATE TABLE IF NOT EXISTS book_genres (
    book_id INTEGER NOT NULL REFERENCES books(id),
    genre_id INTEGER NOT NULL REFERENCES genres(id),
    PRIMARY KEY (book_id, genre_id)
);

CREATE TABLE IF NOT EXISTS recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mood_search_id BIGINT NOT NULL REFERENCES mood_searches(id),
    book_id INTEGER NOT NULL REFERENCES books(id),
    position INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_mood_searches_user_id ON mood_searches(user_id);
CREATE INDEX IF NOT EXISTS idx_recommendations_search_id
    ON recommendations(mood_search_id);
